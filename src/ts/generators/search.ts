/**
 * Local search index generator — produces search.json consumed by client-side Fuse.js.
 * Indexes both metadata (title/excerpt/taxonomies) and the full rendered article text,
 * so keywords anywhere inside a post can be matched.
 */
import Hexo from 'hexo';

interface SearchEntry {
  title: string;
  excerpt: string;
  content: string;
  url: string;
  categories: string[];
  tags: string[];
  type: 'post' | 'page';
}

/**
 * Decode a numeric HTML entity code point without throwing on malformed input.
 */
function decodeCodePoint(code: number): string {
  try {
    return String.fromCodePoint(code);
  } catch {
    return ' ';
  }
}

/**
 * Flatten rendered HTML into a single plain-text string suitable for indexing.
 * Removes scripts/styles, strips tags and decodes HTML entities (named + numeric).
 */
function toPlainText(html: string): string {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&#x([0-9a-f]+);/gi, (_m, hex: string) => decodeCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_m, dec: string) => decodeCodePoint(parseInt(dec, 10)))
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&apos;/gi, "'")
    .replace(/&[a-z][a-z0-9]*;/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function registerSearchGenerator(hexo: Hexo): void {
  hexo.extend.generator.register(
    'search',
    function (locals: {
      posts: {
        filter: (fn: (p: Record<string, unknown>) => boolean) => {
          toArray: () => Record<string, unknown>[];
        };
      };
      pages: {
        filter: (fn: (p: Record<string, unknown>) => boolean) => {
          toArray: () => Record<string, unknown>[];
        };
      };
    }) {
      if (!(hexo.theme.config as any)?.search?.enable) return;

      // Root-relative URLs (respecting config.root) so results work on localhost,
      // preview deploys and sub-path hosting — never hard-code the production origin.
      const urlFor = (path: string): string => {
        const helper = hexo.extend.helper.get('url_for') as unknown as (
          this: Hexo,
          path: string,
        ) => string;
        return helper.call(hexo, path);
      };

      const posts = locals.posts.filter((p) => p.published !== false).toArray();
      const pages = (locals.pages || { filter: () => ({ toArray: () => [] }) })
        .filter((p) => (p as Record<string, unknown>).published !== false)
        .toArray();

      const mapEntry = (item: Record<string, unknown>, type: 'post' | 'page'): SearchEntry => {
        const rawContent: string = (item.content as string) || '';

        // Full plain text of the article body — lets Fuse match any keyword inside it.
        const content = toPlainText(rawContent);

        // Short excerpt for the result preview. Prefer the post's own excerpt
        // (auto-generated by Hexo from <!-- more --> or the first ~100 words).
        const rawExcerpt: string = (item.excerpt as string) || rawContent;
        const excerpt = toPlainText(rawExcerpt).slice(0, 160);

        return {
          title: item.title as string,
          excerpt,
          content,
          url: item.path ? urlFor(item.path as string) : (item.permalink as string) || '',
          categories:
            (
              (item as Record<string, unknown>).categories as { data: { name: string }[] }
            )?.data?.map((c) => c.name) || [],
          tags:
            ((item as Record<string, unknown>).tags as { data: { name: string }[] })?.data?.map(
              (t) => t.name,
            ) || [],
          type,
        };
      };

      const index: SearchEntry[] = [
        ...posts.map((p) => mapEntry(p, 'post')),
        ...pages.map((p) => mapEntry(p, 'page')),
      ];

      return {
        path: 'search.json',
        data: JSON.stringify(index),
      };
    },
  );
}
